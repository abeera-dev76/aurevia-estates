export const formatPrice = (price, currency) => {
  if (!price) return 'Price on Request';
  const curr = currency || 'PKR';
  if (curr.includes('/')) {
    const period = curr.split('/')[1];
    return `PKR ${price.toLocaleString()}/${period}`;
  }
  return `PKR ${price.toLocaleString()}`;
};
